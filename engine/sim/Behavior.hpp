#pragma once

#include "sim/Creature.hpp"

#include <glm/glm.hpp>

namespace wsim::behavior {

// Решение слоя поведения на один тик.
struct Decision {
    glm::vec2 move{0.0f};      // направление (единичный вектор) * доля максимальной скорости [0,1]
    bool      eat    = false;  // можно кормиться (еда в пределах досягаемости)
    bool      rest   = false;  // отдыхает
    bool      mate   = false;  // у партнёра: готово спариваться
    float     alarm  = 0.0f;   // сигнал тревоги наружу (соседи слышат)
    float     matingCall = 0.0f;
    bool      pick   = false;  // у плохого куста: взять ягоды, чтобы подсунуть обидчику
    bool      serve  = false;  // рядом с обидчиком: подсунуть то, что несёт
    bool      chop   = false;  // у дерева: рубит
    int       build  = 0;      // 1 мост, 2 баррикада, 3 ловушка: строит (стоя); где -- buildAt/buildYaw
    glm::vec2 buildAt{};
    float     buildYaw = 0.0f;
    int       craft  = 0;      // 1 -- мастерит копьё, 2 -- щит (на месте)
};

// Слой поведения -- то, что превращает потребности и ощущения в осмысленные действия.
//
// Мозг (случайные веса, эволюция, обучение) остаётся источником индивидуальности, но управляет
// не напрямую, а как модулятор: выходы-желания (eat/flee/mate/rest) масштабируют приоритеты занятий
// (0.65..1.35x), а выходы движения добавляют личный "уклон" к курсу. Базовая разумность -- врождённая
// (как у настоящих животных): сыт -- бродит, голоден -- идёт к еде (или к месту, где её видел), опасность
// -- бежит, устал -- отдыхает, готов -- ищет пару, одинок -- к своим; всё с учётом рельефа.
//
// Мутирует поведенческое состояние существа (behavior/timer/heading/память еды) -- это его "ум".
[[nodiscard]] Decision decide(Creature& c, const SenseInputs& senses, const BrainOutputs& rawBrain, float dt) noexcept;

}  // namespace wsim::behavior
